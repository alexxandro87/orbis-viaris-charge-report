// Generates src/icone.js: the home-screen icon of the site (a charging station inside two arcs, green for energy,
// orange for costs). Usage: node strumenti/icone.mjs   (needs sharp, already in node_modules with wrangler)
import fs from "node:fs";
import sharp from "sharp";

const BG = "#14213d";
const ANELLO = `<g fill="none" stroke-width="9" stroke-linecap="round" transform="rotate(-78 50 50)"><circle cx="50" cy="50" r="33" stroke="#5fd38d" stroke-dasharray="85 122.3"/><circle cx="50" cy="50" r="33" stroke="#f59e0b" stroke-dasharray="85 122.3" stroke-dashoffset="-103.65"/></g>`;
const COLONNINA = `<rect x="38" y="31" width="19" height="38" rx="3" fill="#fff"/><rect x="41.5" y="35" width="12" height="7.5" rx="1.2" fill="${BG}"/><path d="M49.6 46 43.8 56h4.4l-2 8.5 6.6-10.8h-4.4l2.2-7.7z" fill="${BG}"/><path d="M57 47h3.5a2.5 2.5 0 0 1 2.5 2.5V58" fill="none" stroke="#fff" stroke-width="4" stroke-linecap="round"/><rect x="59.5" y="57" width="7" height="8" rx="1.6" fill="#fff"/>`;

// rounded tile (favicon, 192, 512); full background (iPhone 180, maskable with the drawing scaled down)
const svg = ({ tondo = true, scala = 1 } = {}) => {
  const t = scala === 1 ? "" : ` transform="translate(${50 - 50 * scala} ${50 - 50 * scala}) scale(${scala})"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100"${tondo ? ' rx="22"' : ""} fill="${BG}"/><g${t}>${ANELLO}${COLONNINA}</g></svg>`;
};
const png = async (s, lato) => (await sharp(Buffer.from(s), { density: Math.ceil((72 * lato) / 100) + 10 }).resize(lato, lato).png({ compressionLevel: 9 }).toBuffer()).toString("base64");

const out = {
  svg: svg(),
  p180: await png(svg({ tondo: false }), 180),
  p192: await png(svg(), 192),
  p512: await png(svg(), 512),
  p512m: await png(svg({ tondo: false, scala: 0.74 }), 512),
};
fs.writeFileSync("src/icone.js",
  "// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by strumenti/icone.mjs: do not edit by hand. Home-screen icons (PNG in base64).\n" +
  "export const ICONE = " + JSON.stringify(out, null, 1) + ";\n");
console.log("src/icone.js written", Math.round(fs.statSync("src/icone.js").size / 1024) + " KB");
